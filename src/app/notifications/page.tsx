// Proactive compliance alerts: overdue testing, unverified remediation, missing evidence.
// ==============================================================================

import Link from 'next/link';
import {
  Bell,
  Clock,
  AlertTriangle,
  FileCheck,
  Check,
  CheckCheck,
  ExternalLink,
  ShieldAlert,
} from 'lucide-react';
import { dbRepository } from '@/lib/db/sqlite-store';
import { DEMO_ORG, seedDemoData } from '@/lib/demo-data';
import { markNotificationReadAction, markAllNotificationsReadAction } from '@/lib/actions';
export default async function NotificationsPage() {
  seedDemoData(false);
  const orgId = DEMO_ORG.id;
  const notifications = dbRepository.getNotifications(orgId);

  return (
    <div className="space-y-6">
      {/* HEADER */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 pb-3 border-b border-slate-200/80">
        <div>
          <div className="flex items-center gap-2">
            <h1 className="text-xl font-bold text-slate-900 tracking-tight">Notification Center</h1>
            <span className="text-xs font-mono font-semibold px-2.5 py-0.5 rounded-full bg-blue-50 text-blue-700 border border-blue-200">
              {notifications.filter(n => !n.is_read).length} Unread Alerts
            </span>
          </div>
          <p className="text-xs text-slate-500 mt-0.5">
            Automated alerts generated by scheduled monitoring jobs and deterministic gap detection
          </p>
        </div>

        <form action={markAllNotificationsReadAction.bind(null, orgId)}>
          <button
            type="submit"
            className="flex items-center gap-1.5 px-3 py-1.5 bg-white hover:bg-slate-50 text-slate-700 border border-slate-200 rounded-lg text-xs font-semibold shadow-2xs transition-colors"
          >
            <CheckCheck className="w-3.5 h-3.5 text-blue-600" />
            <span>Mark All as Read</span>
          </button>
        </form>
      </div>

      {/* NOTIFICATIONS LIST */}
      <div className="bg-white rounded-xl border border-slate-200/80 overflow-hidden shadow-2xs">
        <div className="divide-y divide-slate-100">
          {notifications.length === 0 ? (
            <div className="p-8 text-center text-xs text-slate-400">
              <Bell className="w-8 h-8 text-slate-300 mx-auto mb-2" />
              <span>You have no notifications at this time.</span>
            </div>
          ) : (
            notifications.map(notif => {
              const priorityClass =
                notif.priority === 'CRITICAL'
                  ? 'bg-rose-100 text-rose-700 border-rose-300'
                  : notif.priority === 'HIGH'
                  ? 'bg-amber-100 text-amber-800 border-amber-300'
                  : 'bg-blue-100 text-blue-800 border-blue-200';

              return (
                <div
                  key={notif.id}
                  className={`p-4 flex items-start justify-between gap-3 transition-colors ${
                    notif.is_read ? 'bg-white hover:bg-slate-50/50' : 'bg-blue-50/30 hover:bg-blue-50/50'
                  }`}
                >
                  <div className="flex items-start gap-3">
                    <div className="mt-0.5">
                      <span className={`font-mono text-[10px] font-bold px-2 py-0.5 rounded border ${priorityClass}`}>
                        {notif.priority}
                      </span>
                    </div>

                    <div className="space-y-1">
                      <div className="flex items-center gap-2">
                        <h3 className="text-xs font-bold text-slate-900">{notif.title}</h3>
                        {!notif.is_read && (
                          <span className="w-2 h-2 rounded-full bg-blue-600" />
                        )}
                      </div>
                      <p className="text-xs text-slate-600 leading-relaxed">{notif.message}</p>
                      <div className="text-[11px] text-slate-400 font-mono">
                        {new Date(notif.created_at).toLocaleString()}
                      </div>
                    </div>
                  </div>

                  <div className="shrink-0 flex items-center gap-2">
                    {notif.link_url && (
                      <Link
                        href={notif.link_url}
                        className="inline-flex items-center gap-1 px-2.5 py-1 text-xs font-semibold text-blue-600 bg-blue-50 hover:bg-blue-100 rounded-md"
                      >
                        <span>View</span>
                        <ExternalLink className="w-3 h-3" />
                      </Link>
                    )}

                    {!notif.is_read && (
                      <form action={markNotificationReadAction.bind(null, notif.id)}>
                        <button
                          type="submit"
                          title="Mark as read"
                          className="p-1.5 text-slate-400 hover:text-slate-600 hover:bg-slate-100 rounded-md"
                        >
                          <Check className="w-3.5 h-3.5" />
                        </button>
                      </form>
                    )}
                  </div>
                </div>
              );
            })
          )}
        </div>
      </div>
    </div>
  );
}
